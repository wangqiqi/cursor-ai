#!/usr/bin/env bash
# Install OpenCode adaptor: generate AGENTS.md + opencode.json (official mechanism).
# OpenCode reads project-root AGENTS.md + opencode.json; it has NO .opencode/ directory convention.
set -euo pipefail

usage() {
  cat <<EOF
用法: $0 <目标项目根> [选项]

生成 OpenCode 官方机制所需文件（见 adaptors/opencode/docs/layout.md）：
  - <目标>/AGENTS.md        项目规则（含 Super Cursor 规则要点）
  - <目标>/opencode.json    instructions 引用 .cursor/rules/*.mdc

前置：目标项目已安装 .cursor/（本 adaptor 依赖其 rules）。

选项:
  --dry-run    只打印将生成的文件，不写磁盘
  -h, --help

环境: SUPER_CURSOR_HOME / CURSOR_AI_HOME（母版仓库根）
EOF
}

resolve_source_root() {
  local candidate _walk
  for candidate in "${SUPER_CURSOR_HOME:-}" "${CURSOR_AI_HOME:-}"; do
    if [[ -n "$candidate" && -d "$candidate/.cursor/harness/core" ]]; then
      echo "$candidate"
      return 0
    fi
  done
  _walk="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
  while [[ "$_walk" != "/" ]]; do
    if [[ -d "$_walk/harness/core" ]]; then
      echo "$(cd "$_walk/.." && pwd)"
      return 0
    fi
    _walk="$(dirname "$_walk")"
  done
  echo "错误: 未找到母版 .cursor/harness/core" >&2
  return 1
}

TARGET=""
DRY_RUN="false"

while [[ $# -gt 0 ]]; do
  case "$1" in
    -h|--help) usage; exit 0 ;;
    --dry-run) DRY_RUN="true"; shift ;;
    -*)
      echo "错误: 未知选项 $1" >&2
      usage
      exit 1
      ;;
    *)
      if [[ -z "$TARGET" ]]; then
        TARGET="$1"
      else
        echo "错误: 多余参数 $1" >&2
        exit 1
      fi
      shift
      ;;
  esac
done

[[ -n "$TARGET" ]] || { echo "错误: 需要目标项目路径" >&2; usage; exit 1; }

SOURCE="$(resolve_source_root)" || exit 1
PACK="$SOURCE/.cursor"
CORE_SRC="$PACK/harness/core"
OC_README="$PACK/adaptors/opencode/README.md"

[[ -d "$CORE_SRC" ]] || { echo "错误: 缺少 $CORE_SRC" >&2; exit 1; }

if [[ "$DRY_RUN" == "true" ]]; then
  echo "DRY RUN: generate $TARGET/AGENTS.md"
  echo "DRY RUN: generate $TARGET/opencode.json (instructions → .cursor/rules/*.mdc)"
  exit 0
fi

mkdir -p "$TARGET"

# 前置检查：依赖 .cursor/rules（OpenCode instructions 引用它）
if [[ ! -d "$TARGET/.cursor/rules" ]]; then
  echo "WARN: 未发现 $TARGET/.cursor/rules — 请先 install-super-cursor（Cursor 安装），再装 opencode" >&2
  echo "      （OpenCode 的 instructions 引用 .cursor/rules/*.mdc；无 .cursor/ 则引用将失效）" >&2
fi

# 1) 生成 AGENTS.md（项目规则入口）
{
  echo "# Project instructions"
  echo ""
  echo "> Generated by Super Cursor adaptor: opencode（源：adaptors/opencode/README.md）"
  echo ""
  echo "This project uses Super Cursor workflow. Key conventions:"
  echo ""
  echo "- Plan before acting: \`/plan\` to slice a Sprint, wait for approval before writing business code."
  echo "- Verify before done: run \`task-verify\` per task, \`verify\` before release (fail-closed)."
  echo "- Project-specific overrides live in \`.growing/\`; installed \`.cursor/\` stays read-only."
  echo ""
  echo "See \`opencode.json\` \`instructions\` for the full rule set (referenced on demand)."
} > "$TARGET/AGENTS.md"

# 2) 生成 opencode.json（instructions 引用 .cursor/rules/*.mdc）
# 使用 python 生成合法 JSON（含 glob 通配的指令文件引用）。
sc_opencode_write_json() {
  local dest="$1"
  local py
  py="$(sc_python 2>/dev/null || true)"
  if [[ -n "$py" ]]; then
    DEST_JSON="$dest" "$py" <<'PY'
import json, os
from pathlib import Path
dest = os.environ["DEST_JSON"]
cfg = {
    "$schema": "https://opencode.ai/config.json",
    "instructions": [
        ".cursor/rules/core.mdc",
        ".cursor/rules/workflow.mdc",
        ".cursor/rules/communication/*.mdc",
        ".cursor/rules/execution/*.mdc",
        ".cursor/rules/feedback/*.mdc",
    ],
}
Path(dest).write_text(json.dumps(cfg, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
PY
    return 0
  fi
  # 无 python 回退：手写 JSON
  cat > "$dest" <<'JSON'
{
  "$schema": "https://opencode.ai/config.json",
  "instructions": [
    ".cursor/rules/core.mdc",
    ".cursor/rules/workflow.mdc",
    ".cursor/rules/communication/*.mdc",
    ".cursor/rules/execution/*.mdc",
    ".cursor/rules/feedback/*.mdc"
  ]
}
JSON
}

# shellcheck source=../lib/platform.sh
source "$CORE_SRC/lib/platform.sh"
sc_opencode_write_json "$TARGET/opencode.json"

echo "OK: OpenCode adaptor 已生成 → $TARGET/AGENTS.md + $TARGET/opencode.json"
